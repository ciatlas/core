/** GitHub's actions.lock (actions-lock.ts): reading the file, and the commit a `uses:` runs within a calling workflow. */
import {
  ACTIONS_LOCK_FILE,
  type ActionsLock,
  type ActionsLockRef,
  actionsLockCommit,
  actionsLockKey,
  readActionsLock,
} from '@ciatlas/core';
import { describe, expect, it } from 'vitest';
import * as browser from '../src/index.browser';
import { WF, yaml } from './helpers';

const A = 'a'.repeat(40);
const B = 'b'.repeat(40);

const CI = `${WF}/ci.yml`;
const RELEASE = `${WF}/release.yml`;

/** A lock with each pin at its commit, and each covered workflow with the pins it uses, as `gh actions-lock` writes it. */
const lockText = (
  pins: Record<string, string>,
  workflows: Record<string, string[]> = { [CI]: Object.keys(pins) },
  version = 'v0.0.3',
) =>
  [
    '# This file is machine-generated by `gh actions-lock`. It should never be edited by hand.',
    '# https://gh.io/actions-lockfile',
    `version: '${version}'`,
    'workflows:',
    ...Object.entries(workflows).flatMap(([file, used]) =>
      used.length ? [`  '${file}':`, ...used.map((p) => `    - '${p}'`)] : [`  '${file}': []`],
    ),
    'dependencies:',
    ...Object.entries(pins).flatMap(([p, sha]) => [
      `  '${p}':`,
      `    ref: '${p.split('@')[1]}'`,
      `    commit: 'sha1-${sha}'`,
      '    owner_id: 1',
      '    repo_id: 2',
    ]),
    '',
  ].join('\n');

function lockOf(text: string): ActionsLock {
  const read = readActionsLock(text);
  if (!read.lock) throw new Error(read.error);
  return read.lock;
}

const action = (owner: string, repo: string, ref: string): ActionsLockRef => ({
  kind: 'action',
  owner,
  repo,
  ref,
});

describe('readActionsLock', () => {
  it('reads the covered workflows and the commit of each pin, keyed by owner/repo@ref in any case', () => {
    const lock = lockOf(lockText({ 'Octo/Setup@v2': A, 'octo/ship@v1': B }));
    expect(lock.version).toBe('v0.0.3');
    expect(lock.workflows).toEqual(new Map([[CI, new Set(['octo/setup@v2', 'octo/ship@v1'])]]));
    expect(lock.commits).toEqual(
      new Map([
        ['octo/setup@v2', A],
        ['octo/ship@v1', B],
      ]),
    );
    expect(actionsLockKey('Octo', 'Setup', 'V2')).toBe('octo/setup@V2');
  });

  it('reads every v0.0.x, ignores keys it does not know, and keys a pin with a path by its repository', () => {
    const text = yaml`
      version: v0.0.1
      hostname: github.com
      workflows:
        ./.github/workflows/ci.yml: [octo/cache/restore@v4]
      dependencies:
        octo/cache/restore@v4: { commit: 'sha1-${A.toUpperCase()}', added_later: true }
    `;
    const lock = lockOf(text);
    expect(lock.workflows.get(CI)).toEqual(new Set(['octo/cache@v4']));
    expect(lock.commits.get('octo/cache@v4')).toBe(A);
  });

  it('leaves out a pin whose commit is in another form, and a key that is no owner/repo@ref', () => {
    const lock = lockOf(
      lockText({ 'octo/setup@v2': A, 'docker://alpine:3': B }).replace(
        `sha1-${A}`,
        `sha256-${'f'.repeat(64)}`,
      ),
    );
    expect(lock.commits).toEqual(new Map());
    expect(lock.workflows.get(CI)).toEqual(new Set(['octo/setup@v2']));
  });

  it('reads a lock with nothing covered yet', () => {
    expect(lockOf("version: 'v0.0.3'\n")).toEqual({
      version: 'v0.0.3',
      workflows: new Map(),
      commits: new Map(),
    });
  });

  it('says why it cannot use a file: YAML, shape or version', () => {
    expect(readActionsLock('version: [').error).toMatch(/^not valid YAML: /);
    expect(readActionsLock('- a list\n').error).toBe('not a workflow dependency lockfile: it has no version');
    expect(readActionsLock('').error).toBe('not a workflow dependency lockfile: it has no version');
    expect(readActionsLock(lockText({ 'octo/setup@v2': A }, undefined, 'v1.0.0'))).toEqual({
      error: 'version v1.0.0 is not one this reader knows (v0.0.x)',
    });
    expect(readActionsLock('version: v0.0.3\nworkflows: { ci.yml: octo/setup@v2 }\n').error).toBe(
      '`workflows` is not a map of workflow files to lists of pins',
    );
    expect(readActionsLock('version: v0.0.3\ndependencies: [octo/setup@v2]\n').error).toBe(
      '`dependencies` is not a map of pins to their commits',
    );
    expect(readActionsLock('version: v0.0.3\ndependencies: { octo/setup@v2: sha1-x }\n').error).toBe(
      '`dependencies` is not a map of pins to their commits',
    );
  });
});

describe('actionsLockCommit', () => {
  const lock = lockOf(
    lockText(
      { 'octo/setup@v2': A, 'octo/ship@v1': B },
      { [CI]: ['octo/setup@v2', 'octo/ship@v1'], [RELEASE]: [] },
    ),
  );

  it("is the pinned commit of an action the calling workflow's list names, in any case and with any path", () => {
    expect(actionsLockCommit(lock, CI, action('octo', 'setup', 'v2'))).toBe(A);
    expect(actionsLockCommit(lock, `./${CI}`, action('OCTO', 'Setup', 'v2'))).toBe(A);
    expect(actionsLockCommit(lock, CI, action('octo', 'ship', 'v1'))).toBe(B);
    expect(actionsLockCommit(lock, CI, action('octo', 'setup', 'v3'))).toBeUndefined();
    expect(actionsLockCommit(lock, CI, action('octo', 'setup', 'V2'))).toBeUndefined();
  });

  // UNVERIFIED until simulci's lab case R9: that GitHub runs a pin only in a covered workflow whose list names it.
  it('is no commit in a workflow the lock does not cover, or whose list lacks the pin', () => {
    expect(actionsLockCommit(lock, `${WF}/other.yml`, action('octo', 'setup', 'v2'))).toBeUndefined();
    expect(actionsLockCommit(lock, RELEASE, action('octo', 'setup', 'v2'))).toBeUndefined();
  });

  it('is no commit for a reusable workflow call, which actions.lock does not pin', () => {
    const call: ActionsLockRef = { kind: 'workflow', owner: 'octo', repo: 'ship', ref: 'v1' };
    expect(actionsLockCommit(lock, CI, call)).toBeUndefined();
  });

  it('is no commit without a lock, or for a pin listed with no usable commit', () => {
    expect(actionsLockCommit(undefined, CI, action('octo', 'setup', 'v2'))).toBeUndefined();
    const unpinned = lockOf(lockText({ 'octo/setup@v2': A }, { [CI]: ['octo/setup@v2', 'octo/other@v1'] }));
    expect(actionsLockCommit(unpinned, CI, action('octo', 'other', 'v1'))).toBeUndefined();
  });

  it('is the same from the browser entry', () => {
    expect(browser.ACTIONS_LOCK_FILE).toBe(ACTIONS_LOCK_FILE);
    const read = browser.readActionsLock(lockText({ 'octo/setup@v2': A }));
    expect(browser.actionsLockCommit(read.lock, CI, action('octo', 'setup', 'v2'))).toBe(A);
  });
});
