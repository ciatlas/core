/** Locale-independent ordering, so contracts are byte-identical on every machine. */
export const byCodePoint = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const sortedRecord = <T>(rec: Record<string, T>): Record<string, T> =>
  Object.fromEntries(Object.entries(rec).sort(([a], [b]) => byCodePoint(a, b)));

const bindingText = (b: Binding): string =>
  b.site ? b.site.text : typeof b.value === 'string' ? b.value : JSON.stringify(b.value);

function inputContract(i: InputDecl): ContractInput {
  return {
    ...(i.type ? { type: i.type } : {}),
    required: i.required,
    ...(i.hasDefault ? { default: i.default as Json } : {}),
    ...(i.description ? { description: i.description } : {}),
    ...(i.options ? { options: i.options } : {}),
  };
}

const stepRef = (s: { id?: string; index: number }) => s.id ?? `#${s.index + 1}`;

function workflowInterface(wf: WorkflowDecl): Contract['interface'] {
  const inputs: Record<string, ContractInput> = {};
  for (const i of Object.values(wf.call?.inputs ?? {})) inputs[i.name] = inputContract(i);
  const dispatchInputs: Record<string, ContractInput> = {};
  for (const i of Object.values(wf.dispatch?.inputs ?? {})) dispatchInputs[i.name] = inputContract(i);
  const secrets: Record<string, { required: boolean }> = {};
  for (const s of Object.values(wf.call?.secrets ?? {})) secrets[s.name] = { required: s.required };
  const outputs: Contract['interface']['outputs'] = {};
  for (const o of Object.values(wf.call?.outputs ?? {})) {
    outputs[o.name] = {
      ...(o.description ? { description: o.description } : {}),
      ...(o.value !== undefined
        ? { value: typeof o.value === 'string' ? o.value : JSON.stringify(o.value) }
        : {}),
    };
  }
  return {
    inputs: sortedRecord(inputs),
    ...(Object.keys(dispatchInputs).length ? { dispatchInputs: sortedRecord(dispatchInputs) } : {}),
    ...(Object.keys(secrets).length ? { secrets: sortedRecord(secrets) } : {}),
    outputs: sortedRecord(outputs),
  };
}

function actionInterface(a: ActionDecl): Contract['interface'] {
  const inputs: Record<string, ContractInput> = {};
  for (const i of Object.values(a.inputs)) inputs[i.name] = inputContract(i);
  const outputs: Contract['interface']['outputs'] = {};
  for (const o of Object.values(a.outputs)) {
    outputs[o.name] = {
      ...(o.description ? { description: o.description } : {}),
      ...(o.value !== undefined
        ? { value: typeof o.value === 'string' ? o.value : JSON.stringify(o.value) }
        : {}),
    };
  }
  return { inputs: sortedRecord(inputs), outputs: sortedRecord(outputs) };
}

function consumersOf(index: ProjectIndex, unit: UnitDecl): Contract['consumers'] {
  const out: Contract['consumers'] = [];
  if (unit.kind === 'workflow') {
    for (const c of index.callersOf(unit.path)) {
      const reads = Object.keys(unit.call?.outputs ?? {}).filter(
        (o) => index.usagesOf(sym.jobOutput(c.caller.path, c.job.id, o)).length > 0,
      );
      out.push({
        from: c.caller.path,
        job: c.job.id,
        passes: Object.keys(c.job.with).sort(),
        reads: reads.sort(),
      });
    }
  } else {
    for (const u of index.usersOf(unit.path)) {
      const reads = u.step.id
        ? Object.keys(unit.outputs).filter(
            (o) => index.usagesOf(sym.stepOutput(u.unit.path, u.job?.id, u.step.id!, o)).length > 0,
          )
        : [];
      out.push({
        from: u.unit.path,
        ...(u.job ? { job: u.job.id } : {}),
        step: stepRef(u.step),
        passes: Object.keys(u.step.with).sort(),
        reads: reads.sort(),
      });
    }
  }
  return out.sort((a, b) =>
    byCodePoint(`${a.from}#${a.job ?? ''}#${a.step ?? ''}`, `${b.from}#${b.job ?? ''}#${b.step ?? ''}`),
  );
}

function callsOf(wf: WorkflowDecl): Contract['calls'] {
  const calls: NonNullable<Contract['calls']> = [];
  for (const job of Object.values(wf.jobs)) {
    if (!job.uses) continue;
    const exp = job.matrix ? expandMatrix(job.matrix) : undefined;
    const withs = Object.fromEntries(Object.values(job.with).map((b) => [b.name, bindingText(b)]));
    const secrets = job.secretsInherit
      ? ('inherit' as const)
      : Object.fromEntries(Object.values(job.secrets).map((b) => [b.name, bindingText(b)]));
    calls.push({
      job: job.id,
      uses: job.uses.target ?? job.uses.raw,
      ...(Object.keys(withs).length ? { with: sortedRecord(withs) } : {}),
      ...(secrets === 'inherit' || Object.keys(secrets).length
        ? { secrets: secrets === 'inherit' ? secrets : sortedRecord(secrets) }
        : {}),
      ...(job.needs.length ? { needs: job.needs.map((n) => n.id).sort() } : {}),
      ...(exp && !exp.dynamic
        ? { matrix: { combinations: exp.combos.length, keys: [...exp.keys].sort(), exact: exp.exact } }
        : exp?.dynamic
          ? { matrix: { combinations: 0, keys: [], exact: false } }
          : {}),
    });
  }
  return calls.sort((a, b) => byCodePoint(a.job, b.job));
}

function usesOf(index: ProjectIndex, unit: UnitDecl): Contract['uses'] {
  const uses: NonNullable<Contract['uses']> = [];
  for (const u of index.actionUses.filter((x) => x.unit === unit)) {
    const withs = Object.fromEntries(Object.values(u.step.with).map((b) => [b.name, bindingText(b)]));
    uses.push({
      ...(u.job ? { job: u.job.id } : {}),
      step: stepRef(u.step),
      uses: u.action.path,
      ...(Object.keys(withs).length ? { with: sortedRecord(withs) } : {}),
    });
  }
  return uses.sort((a, b) => byCodePoint(`${a.job ?? ''}#${a.step}`, `${b.job ?? ''}#${b.step}`));
}

export function buildContract(index: ProjectIndex, unit: UnitDecl): Contract {
  const calls = unit.kind === 'workflow' ? callsOf(unit) : [];
  const uses = usesOf(index, unit);
  return {
    $schema: schemaUrl('contract'),
    version: SCHEMA_VERSIONS.contract,
    kind: unit.kind,
    path: unit.path,
    ...(unit.name ? { name: unit.name } : {}),
    ...(unit.kind === 'workflow' ? { triggers: [...unit.triggers].sort() } : {}),
    interface: unit.kind === 'workflow' ? workflowInterface(unit) : actionInterface(unit),
    ...(calls?.length ? { calls } : {}),
    ...(uses?.length ? { uses } : {}),
    consumers: consumersOf(index, unit),
  };
}

export function serializeContract(c: Contract): string {
  return `${CONTRACT_HEADER}${stringify(c, { lineWidth: 0, indent: 2, defaultStringType: 'PLAIN', singleQuote: true })}`;
}

/**
 * Repo-relative contract file for a unit:
 * `.github/workflows/ci.yml` → `.github/flowpact/contracts/workflows/ci.contract.yml`,
 * `.github/actions/setup` → `.github/flowpact/contracts/actions/setup.contract.yml`,
 * `tools/build` → `.github/flowpact/contracts/actions/tools__build.contract.yml`.
 */
export function contractFileFor(
  unit: Pick<UnitDecl, 'kind' | 'path'>,
  taken: Set<string> = new Set(),
  dir: string = CONTRACTS_DIR,
): string {
  const fileOf = (base: string) => `${dir}/${base}.contract.yml`;
  let base: string;
  if (unit.kind === 'workflow') {
    base = `workflows/${unit.path
      .split('/')
      .pop()!
      .replace(/\.ya?ml$/i, '')}`;
    if (taken.has(fileOf(base))) base = `workflows/${unit.path.split('/').pop()!}`;
  } else {
    const rel = unit.path.replace(/^\.github\/actions\//, '').replace(/^\.$/, 'root');
    base = `actions/${rel.split('/').join('__')}`;
  }
  // Paths that flatten to the same name (`tools/build` and `.github/actions/tools/build`) get a numeric suffix.
  const stem = base;
  for (let n = 2; taken.has(fileOf(base)); n++) base = `${stem}-${n}`;
  return fileOf(base);
}

