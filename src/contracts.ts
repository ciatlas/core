export const CONTRACTS_DIR = `${CONFIG_DIR}/contracts`;

/** A contract as flowpact writes it: checkouts with core.autocrlf turn LF into CRLF. */
export function normalizeContractText(text: string): string {
  return text.replace(/\r\n/g, '\n');
}
export const CONTRACT_HEADER =
  '# Generated by flowpact — do not edit by hand. Run `flowpact generate` to update.\n# Docs: https://rumankazi.github.io/flowpact/docs/contracts\n';

