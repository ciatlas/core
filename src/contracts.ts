const contractInputSchema = z
  .object({
    type: z.string().optional(),
    required: z.boolean(),
    default: z.json().optional(),
    description: z.string().optional(),
    options: z.array(z.string()).optional(),
  })
  .strict();

const contractCallSchema = z
  .object({
    job: z.string(),
    uses: z.string(),
    with: z.record(z.string(), z.string()).optional(),
    secrets: z.union([z.literal('inherit'), z.record(z.string(), z.string())]).optional(),
    needs: z.array(z.string()).optional(),
    matrix: z
      .object({ combinations: z.number().int(), keys: z.array(z.string()), exact: z.boolean() })
      .strict()
      .optional(),
  })
  .strict();

const contractUseSchema = z
  .object({
    job: z.string().optional(),
    step: z.string(),
    uses: z.string(),
    with: z.record(z.string(), z.string()).optional(),
  })
  .strict();

const contractConsumerSchema = z
  .object({
    from: z.string(),
    job: z.string().optional(),
    step: z.string().optional(),
    passes: z.array(z.string()),
    reads: z.array(z.string()),
  })
  .strict();

export const contractSchema = z
  .object({
    $schema: z.string(),
    version: z.literal(SCHEMA_VERSIONS.contract),
    kind: z.enum(['workflow', 'action']),
    path: z.string(),
    name: z.string().optional(),
    triggers: z.array(z.string()).optional(),
    interface: z
      .object({
        /** `workflow_call` inputs for workflows, `inputs` for actions. */
        inputs: z.record(z.string(), contractInputSchema),
        /** `workflow_dispatch` inputs (workflows only). */
        dispatchInputs: z.record(z.string(), contractInputSchema).optional(),
        secrets: z.record(z.string(), z.object({ required: z.boolean() }).strict()).optional(),
        outputs: z.record(
          z.string(),
          z.object({ description: z.string().optional(), value: z.string().optional() }).strict(),
        ),
      })
      .strict(),
    calls: z.array(contractCallSchema).optional(),
    uses: z.array(contractUseSchema).optional(),
    consumers: z.array(contractConsumerSchema),
  })
  .strict();

export type Contract = z.infer<typeof contractSchema>;
export type ContractInput = z.infer<typeof contractInputSchema>;

export function contractJsonSchema(): Record<string, unknown> {
  return { $id: schemaUrl('contract'), title: 'flowpact contract', ...z.toJSONSchema(contractSchema) };
}

